var aliases = map[rune]rune{'–': '-', '—': '-', '−': '-', '×': 'x', '…': '.'}

const (
	GlyphWidth  = 5
	GlyphHeight = 7
)

// glyphBits holds each ASCII glyph's rows, the leftmost column in bit 4; every glyph
// in the font is ASCII.
var glyphBits = func() (bits [128]*[GlyphHeight]uint8) {
	for char, art := range glyphArt {
		var rows [GlyphHeight]uint8
		for row, line := range strings.Split(art, "|") {
			for i, cell := range line {
				if cell == '#' {
					rows[row] |= 1 << (4 - i)
				}
			}
		}
		bits[char] = &rows
	}
	return bits
}()

func glyph(r rune) *[GlyphHeight]uint8 {
	if alias, ok := aliases[r]; ok {
		r = alias
	}
	if r >= 0 && r < 128 && glyphBits[r] != nil {
		return glyphBits[r]
	}
	return glyphBits['?']
}

// TextWidth is the width of text in pixels. Advance per character is six columns: five
// for the glyph and one of spacing.
func TextWidth(text string, scale int) int {
	return max(0, utf8.RuneCountInString(text)*6*scale-scale)
}

func TextHeight(scale int) int { return GlyphHeight * scale }

// FillRect paints the rectangle at (x, y) of w x h pixels, clipped to the image.
func FillRect(rgb []byte, width, height, x, y, w, h int, color [3]byte) {
	x0, y0 := max(0, x), max(0, y)
	x1, y1 := min(width, x+w), min(height, y+h)
	if x1 <= x0 || y1 <= y0 {
		return
	}
	// One row pixel by pixel, the others copied from it: a sheet's background is a memcpy a row.
	first := (y0*width + x0) * 3
	line := rgb[first : first+(x1-x0)*3]
	for at := 0; at < len(line); at += 3 {
		line[at], line[at+1], line[at+2] = color[0], color[1], color[2]
	}
	for row := y0 + 1; row < y1; row++ {
		copy(rgb[(row*width+x0)*3:], line)
	}
}

// DrawText draws text with its top-left corner at (x, y); characters outside the font
// draw as "?".
func DrawText(rgb []byte, width, height, x, y int, text string, scale int, color [3]byte) {
	cursor := x
	for _, r := range text {
		rows := glyph(r)
		for row := range GlyphHeight {
			for col := range GlyphWidth {
				if rows[row]&(1<<(4-col)) != 0 {
					FillRect(rgb, width, height, cursor+col*scale, y+row*scale, scale, scale, color)
				}
			}
		}
		cursor += 6 * scale
	}
}
